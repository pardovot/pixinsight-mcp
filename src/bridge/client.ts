import { randomUUID } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readdir, readFile, rename, stat, unlink, utimes, writeFile } from "node:fs/promises";
import { spawn } from "node:child_process";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { setTimeout as delay } from "node:timers/promises";
import { configFromEnv, type BridgeConfig } from "../config.js";
import { pixinsightExecutable, runningPixInsightProcesses, toPixInsightPath } from "../pixinsight.js";
import { currentCallContext } from "./call-context.js";
import type { BridgeCommand, BridgeFailure, BridgeResult } from "./protocol.js";

// Generated by scripts/build-pjsr-bundle.mjs next to the compiled server.
const bundlePath = join(dirname(fileURLToPath(import.meta.url)), "..", "pjsr", "mcp-handlers.js");

// The PixInsight client started for each command exits within about a second
// of handing the request over, even while the instance is busy. One still
// alive after this long is waiting on PixInsight's modal "instance is not
// running" error, and killing it also closes that dialog.
const HANDOFF_TIMEOUT_MS = 15_000;

// Bridge files older than this belong to a session that died. A waiting call keeps its command and
// driver fresh until the command starts, and needs neither after that.
const STALE_FILE_MS = 600_000;

// A waiting call refreshes its command's heartbeat this often, and a command whose heartbeat is
// older than ABANDONED_MS does not run: the server that wrote it gave up or died, and a save or
// close must not fire long after. The heartbeat is a field the driver reads anyway, not the driver's
// modification time: reading that through FileInfo makes CorrectMagentaStars' Execute and Close
// loop spin in a later Script run.
const HEARTBEAT_MS = 10_000;
const ABANDONED_MS = 60_000;

// How often a waiting call checks that PixInsight is still running. A process list takes about
// 0.2 s on Windows.
const LIVENESS_CHECK_MS = 2_000;

// How often a waiting call reports progress, when the client asked for it.
const PROGRESS_INTERVAL_MS = 10_000;
const MS_PER_SECOND = 1_000;

// How long a result file may stay unparseable before it counts as malformed
// rather than caught half written.
const MALFORMED_GRACE_MS = 2_000;

// `#engine v8` at the start of a line selects PixInsight's V8 engine, a script
// without it runs on the legacy engine.
const V8_DIRECTIVE = /^#engine\s+v8\b/m;

/**
 * The globals an included script sees replaced, the parameters of the driver's
 * runIncludedScript. pjsr/scripts.js passes a substitute for each, or the real
 * global, and refuses to run when it builds a substitute for a name missing here.
 */
export const SCRIPT_SHADOWED_NAMES = [
  "Parameters", "Dialog", "MessageBox", "console",
  "OpenFileDialog", "SaveFileDialog", "GetDirectoryDialog", "ColorDialog", "FontDialog",
];

export interface DriverFiles {
  bundlePath: string;
  commandPath: string;
  /** Written with PixInsight's process id when the command starts. */
  startedPath: string;
  resultPath: string;
  /** The script a run_script driver includes, with its source to pick the engine. */
  script?: { path: string; source: string };
}

/**
 * The driver script for one command: include the bundle, run the command,
 * write the result. A run_script driver runs on the engine the script declares:
 * the legacy engine cannot parse V8 syntax such as class, and on V8 the legacy
 * pjsr includes redeclare classes the V8 bootstrap preloads. It includes the
 * script inside a function, whose parameters shadow the globals in
 * SCRIPT_SHADOWED_NAMES and which keeps the script's own top level
 * declarations out of PixInsight's persistent global scope.
 */
export function driverSource(files: DriverFiles): string {
  const quoted = (path: string) => {
    const pixinsightPath = toPixInsightPath(path);
    // A double quote or line break would end the #include string early.
    if (/["\r\n]/.test(pixinsightPath)) throw new Error(`Path not usable in a PixInsight #include: ${path}`);
    return `"${pixinsightPath}"`;
  };
  const header = [`#include ${quoted(files.bundlePath)}`];
  if (files.script) {
    if (V8_DIRECTIVE.test(files.script.source)) header.unshift("#engine v8");
    header.push(
      `function runIncludedScript( ${SCRIPT_SHADOWED_NAMES.join(", ")} ) {`,
      `#include ${quoted(files.script.path)}`,
      `}`,
      `runIncludedScript.shadowedNames = ${JSON.stringify(SCRIPT_SHADOWED_NAMES)};`,
    );
  }
  return [
    ...header,
    `var __started = Date.now();`,
    `var __command = JSON.parse( File.readTextFile( ${quoted(files.commandPath)} ) );`,
    `if ( __started - __command.heartbeat <= ${ABANDONED_MS} ) {`,
    // The process id lets the server tell a long command from a crashed PixInsight.
    `   File.writeTextFile( ${quoted(files.startedPath + ".tmp")}, JSON.stringify( { pid: CoreApplication.pid } ) );`,
    `   File.move( ${quoted(files.startedPath + ".tmp")}, ${quoted(files.startedPath)} );`,
    `   var __result;`,
    `   try {`,
    `      var __handled = dispatchCommand( __command );`,
    `      __result = { id: __command.id, status: __handled.status, duration_ms: Date.now() - __started,`,
    `                   outputs: __handled.outputs, message: __handled.message || "" };`,
    `   } catch ( __error ) {`,
    `      __result = { id: __command.id, status: "error", duration_ms: Date.now() - __started,`,
    `                   error: { message: String( __error.message || __error ),`,
    `                            type: __error.name || "Error", stack: __error.stack || "" } };`,
    `   }`,
    // Renamed into place, so the server never reads a partial result.
    `   File.writeTextFile( ${quoted(files.resultPath + ".tmp")}, JSON.stringify( __result ) );`,
    `   File.move( ${quoted(files.resultPath + ".tmp")}, ${quoted(files.resultPath)} );`,
    `}`,
    "",
  ].join("\n");
}

/**
 * Hands a written command to PixInsight. Injectable so tests can drive the
 * polling and result handling without launching the application.
 */
export type CommandDispatcher = (
  command: BridgeCommand, commandPath: string, script: IncludedScript | undefined, slot: number | null,
) => Promise<void>;

/**
 * The script file a run_script driver includes, and the command line arguments it reads, as
 * Runtime.jsArguments on V8 and jsArguments on the legacy engine.
 */
export interface IncludedScript {
  path: string;
  arguments: string[];
}

export interface CallOptions {
  /** View a process runs on. Omitted, the process runs globally. */
  targetView?: string | null;
  timeoutMs?: number;
  /** The script the driver includes, for run_script. */
  script?: IncludedScript;
  /** Instance slot for this call alone, or null for the first running instance. Omitted, the client's slot. */
  instance?: number | null;
}

// PixInsight splits a -x script's argument list at commas.
const ARGUMENT_SEPARATOR = ",";

/** The -x handoff for a driver: the instance slot, the driver's path and the included script's arguments. */
export function handoffArgument(slot: number | null, driverPath: string, scriptArguments: string[] = []): string {
  const unusable = scriptArguments.find((argument) => argument.includes(ARGUMENT_SEPARATOR) || /[\r\n"]/.test(argument));
  if (unusable !== undefined)
    throw new Error(`Script argument not usable on the PixInsight command line, it holds a comma, quote or line break: ${unusable}`);
  const target = slot === null ? "" : `${slot}:`;
  return `-x=${target}${[toPixInsightPath(driverPath), ...scriptArguments].join(ARGUMENT_SEPARATOR)}`;
}

function errorResult(id: string, started: number, type: string, message: string): BridgeFailure {
  return { id, status: "error", duration_ms: Date.now() - started, error: { type, message } };
}

function isMissingFile(error: unknown): boolean {
  return error instanceof Error && "code" in error && error.code === "ENOENT";
}

async function removeQuietly(path: string): Promise<void> {
  try {
    await unlink(path);
  } catch (error: unknown) {
    if (!isMissingFile(error))
      console.error(`[pixinsight-mcp] could not remove ${path}: ${String(error)}`);
  }
}

/** Gives a file the current time, so cleanStaleFiles leaves it. A missing file stays missing. */
async function touch(path: string): Promise<void> {
  const now = new Date();
  try {
    await utimes(path, now, now);
  } catch (error: unknown) {
    if (!isMissingFile(error)) throw error;
  }
}

/** Renamed into place, so the driver never reads a partial command. */
async function writeCommand(commandPath: string, command: BridgeCommand): Promise<void> {
  await writeFile(`${commandPath}.tmp`, JSON.stringify(command), "utf-8");
  await rename(`${commandPath}.tmp`, commandPath);
}

/**
 * The process id in a started marker, null when it names none, undefined while the command has not
 * started.
 */
async function startedProcessId(startedPath: string): Promise<number | null | undefined> {
  let text: string;
  try {
    text = await readFile(startedPath, "utf-8");
  } catch (error: unknown) {
    if (isMissingFile(error)) return undefined;
    throw error;
  }
  // CoreApplication.pid is a string on the legacy engine.
  const { pid } = JSON.parse(text) as { pid?: unknown };
  const processId = typeof pid === "string" ? Number(pid) : pid;
  return typeof processId === "number" && Number.isInteger(processId) ? processId : null;
}

/** Lists the running PixInsight process ids, or null when the list cannot be read. */
export type ProcessLister = () => Promise<number[] | null>;

/** What tests replace: the handoff, the process list and how often a waiting call refreshes its heartbeat. */
export interface BridgeClientOptions {
  dispatch?: CommandDispatcher;
  listProcesses?: ProcessLister;
  heartbeatMs?: number;
}

export class BridgeClient {
  private config: BridgeConfig;
  private readonly dispatcher: CommandDispatcher;
  private readonly listProcesses: ProcessLister;
  private readonly heartbeatMs: number;
  private readonly commandsDir: string;
  private readonly scriptsDir: string;
  private readonly resultsDir: string;

  constructor(config?: Partial<BridgeConfig>, options?: BridgeClientOptions) {
    this.config = { ...configFromEnv(), ...config };
    this.dispatcher = options?.dispatch ?? ((command, path, script, slot) => this.dispatch(command, path, script, slot));
    this.listProcesses = options?.listProcesses ?? runningPixInsightProcesses;
    this.heartbeatMs = options?.heartbeatMs ?? HEARTBEAT_MS;
    this.commandsDir = join(this.config.bridgeDir, "commands");
    this.scriptsDir = join(this.config.bridgeDir, "scripts");
    this.resultsDir = join(this.config.bridgeDir, "results");
  }

  get bridgeDir(): string {
    return this.config.bridgeDir;
  }

  /**
   * Target a PixInsight instance slot (as started with -n=N), or null for the
   * first running instance. A call reads the slot when it is handed over, so a
   * switch applies to the calls made after it.
   */
  setInstance(slot: number | null): void {
    this.config = { ...this.config, instance: slot };
  }

  getInstance(): number | null {
    return this.config.instance;
  }

  async ensureDirectories(): Promise<void> {
    for (const dir of [this.commandsDir, this.scriptsDir, this.resultsDir])
      await mkdir(dir, { recursive: true });
  }

  /** Run one bridge verb in PixInsight and wait for its result. */
  async call<Outputs = Record<string, unknown>>(
    tool: string, parameters: Record<string, unknown> = {}, options: CallOptions = {},
  ): Promise<BridgeResult<Outputs>> {
    await this.ensureDirectories();
    const command: BridgeCommand = {
      id: randomUUID(),
      timestamp: new Date().toISOString(),
      tool,
      parameters,
      targetView: options.targetView ?? null,
      heartbeat: Date.now(),
    };
    const started = Date.now();
    const commandPath = join(this.commandsDir, `${command.id}.json`);
    await writeCommand(commandPath, command);

    try {
      try {
        const slot = options.instance === undefined ? this.config.instance : options.instance;
        await this.dispatcher(command, commandPath, options.script, slot);
      } catch (error: unknown) {
        return errorResult(command.id, started, "DispatchError",
          error instanceof Error ? error.message : String(error));
      }
      return await this.waitForResult<Outputs>(command, started, options.timeoutMs ?? this.config.defaultTimeoutMs);
    } finally {
      await removeQuietly(commandPath);
      await removeQuietly(join(this.scriptsDir, `${command.id}.js`));
      await removeQuietly(join(this.resultsDir, `${command.id}.started`));
    }
  }

  /**
   * Run one bridge verb and return its outputs, throwing the handler's error message on failure.
   * The caller states the outputs' shape, which is the handler's contract in pjsr/.
   */
  async request<Outputs>(tool: string, parameters: Record<string, unknown> = {}, options: CallOptions = {}): Promise<Outputs> {
    const result = await this.call<Outputs>(tool, parameters, options);
    if (result.status === "error") throw new Error(result.error.message);
    return result.outputs;
  }

  /**
   * Hand one command to the running PixInsight instance.
   *
   * PJSR has no way to keep a listener alive: a script holds the main thread
   * until it returns, and modeless script interfaces do not exist, so nothing
   * of ours can sit waiting inside PixInsight. Instead each command is a short
   * script delivered through the core application's documented command line
   * interface, which runs it in the user's own session and returns. Requests
   * that arrive while PixInsight is busy are queued by the core application,
   * so a long process delays a command but never loses it.
   */
  private async dispatch(
    command: BridgeCommand, commandPath: string, included: IncludedScript | undefined, slot: number | null,
  ): Promise<void> {
    if (!existsSync(bundlePath))
      throw new Error(`Handler bundle missing: ${bundlePath}. Run npm run build.`);

    const running = await this.listProcesses();
    if (running !== null && running.length === 0)
      throw new Error("PixInsight is not running. Start PixInsight and try again.");

    const resultPath = join(this.resultsDir, `${command.id}.json`);
    const startedPath = join(this.resultsDir, `${command.id}.started`);
    const scriptPath = join(this.scriptsDir, `${command.id}.js`);
    const script = included === undefined ? undefined : { path: included.path, source: await readFile(included.path, "utf-8") };
    const handoff = handoffArgument(slot, scriptPath, included?.arguments);
    await writeFile(scriptPath,
      driverSource({ bundlePath, commandPath, startedPath, resultPath, script }), "utf-8");

    const executable = pixinsightExecutable();
    await new Promise<void>((resolveHandoff, rejectHandoff) => {
      const client = spawn(executable, [handoff], {
        stdio: "ignore",
        windowsHide: true,
      });
      const watchdog = setTimeout(() => {
        client.kill();
        rejectHandoff(new Error(slot === null
          ? `PixInsight did not accept the command within ${HANDOFF_TIMEOUT_MS / MS_PER_SECOND}s.`
          : `PixInsight instance ${slot} is not running. Use list_instances and use_instance to pick a running one.`));
      }, HANDOFF_TIMEOUT_MS);
      client.on("error", (error: NodeJS.ErrnoException) => {
        clearTimeout(watchdog);
        rejectHandoff(new Error(error.code === "ENOENT"
          ? `PixInsight not found at ${executable}. Set PI_ROOT or PIXINSIGHT_EXE.`
          : `Could not run ${executable}: ${error.message}`));
      });
      client.on("exit", (code) => {
        clearTimeout(watchdog);
        if (code === 0 || code === null) resolveHandoff();
        else rejectHandoff(new Error(`PixInsight refused the command (exit code ${code}).`));
      });
    });
  }

  /**
   * Waits for the command's result as long as PixInsight runs, with no time limit unless one is
   * given: a command may queue behind other work and then run for hours. Ends early when
   * PixInsight exits, or when the client cancels the request.
   */
  private async waitForResult<Outputs>(command: BridgeCommand, started: number, timeoutMs: number | null): Promise<BridgeResult<Outputs>> {
    const id = command.id;
    const resultPath = join(this.resultsDir, `${id}.json`);
    const startedPath = join(this.resultsDir, `${id}.started`);
    const commandPath = join(this.commandsDir, `${id}.json`);
    const { signal, reportProgress } = currentCallContext();
    let unparseableSince: number | null = null;
    let runningProcess: number | null | undefined;
    let lastHeartbeat = started;
    let lastLivenessCheck = started;
    let lastProgress = started;

    for (;;) {
      if (existsSync(resultPath)) {
        let text = "";
        try {
          text = await readFile(resultPath, "utf-8");
          const result = JSON.parse(text) as BridgeResult<Outputs>;
          await removeQuietly(resultPath);
          return result;
        } catch {
          // A partial write gets a short grace, a result that stays broken is
          // reported instead of waited out.
          unparseableSince ??= Date.now();
          if (Date.now() - unparseableSince >= MALFORMED_GRACE_MS) {
            await removeQuietly(resultPath);
            return errorResult(id, started, "MalformedResult",
              "PixInsight delivered a result that is not valid JSON, the command likely ran but its " +
                "result was corrupted. Check the image state before retrying. Raw result (truncated): " +
                JSON.stringify(text.slice(0, 200)));
          }
        }
      }

      const now = Date.now();
      if (signal?.aborted)
        return errorResult(id, started, "Cancelled",
          "The call was cancelled. A command PixInsight had not started never runs, one already running finishes on its own.");
      if (timeoutMs !== null && now - started >= timeoutMs)
        return errorResult(id, started, "Timeout", runningProcess === undefined
          ? `PixInsight did not start the command within ${timeoutMs}ms. It runs a request only when its main ` +
            `thread is free, so it is still starting up, busy with a long process, or showing a dialog.`
          : `PixInsight started the command but did not finish it within ${timeoutMs}ms.`);

      if (runningProcess === undefined) {
        try {
          runningProcess = await startedProcessId(startedPath);
        } catch (error: unknown) {
          console.error(`[pixinsight-mcp] unreadable started marker ${startedPath}: ${String(error)}`);
          runningProcess = null;
        }
      }
      if (runningProcess === undefined && now - lastHeartbeat >= this.heartbeatMs) {
        lastHeartbeat = now;
        command.heartbeat = now;
        try {
          await writeCommand(commandPath, command);
          await touch(join(this.scriptsDir, `${id}.js`));
        } catch (error: unknown) {
          console.error(`[pixinsight-mcp] could not refresh the heartbeat of ${commandPath}: ${String(error)}`);
        }
      }
      if (now - lastLivenessCheck >= LIVENESS_CHECK_MS) {
        lastLivenessCheck = now;
        if (await this.pixinsightExited(runningProcess) && !existsSync(resultPath))
          return errorResult(id, started, "PixInsightExited", runningProcess === undefined
            ? "PixInsight exited before it started the command."
            : "PixInsight exited while it ran the command, most likely a crash. Restart PixInsight, image changes not saved are lost.");
      }
      if (reportProgress && now - lastProgress >= PROGRESS_INTERVAL_MS) {
        lastProgress = now;
        const seconds = Math.round((now - started) / MS_PER_SECOND);
        const message = runningProcess === undefined
          ? `Waiting ${seconds} s for PixInsight to finish earlier work and start ${command.tool}`
          : `PixInsight has been running ${command.tool} for ${seconds} s`;
        try {
          await reportProgress(seconds, message);
        } catch (error: unknown) {
          console.error(`[pixinsight-mcp] could not report progress: ${String(error)}`);
        }
      }
      await delay(this.config.pollIntervalMs);
    }
  }

  /**
   * Whether PixInsight is gone: the process that started the command, or before it starts, every
   * instance. Instances are not told apart before the start, so a queued command to a slot whose
   * instance exits while another runs waits on.
   */
  private async pixinsightExited(runningProcess: number | null | undefined): Promise<boolean> {
    const processes = await this.listProcesses();
    if (processes === null) return false;
    return typeof runningProcess === "number" ? !processes.includes(runningProcess) : processes.length === 0;
  }

  /** Remove command, script and result files a dead session left behind. Returns how many. */
  async cleanStaleFiles(): Promise<number> {
    let removed = 0;
    for (const dir of [this.commandsDir, this.scriptsDir, this.resultsDir]) {
      let names: string[];
      try {
        names = await readdir(dir);
      } catch (error: unknown) {
        if (isMissingFile(error)) continue;
        throw error;
      }
      for (const name of names) {
        const path = join(dir, name);
        try {
          if (Date.now() - (await stat(path)).mtimeMs <= STALE_FILE_MS) continue;
        } catch (error: unknown) {
          if (isMissingFile(error)) continue;
          throw error;
        }
        await removeQuietly(path);
        removed++;
      }
    }
    return removed;
  }
}
